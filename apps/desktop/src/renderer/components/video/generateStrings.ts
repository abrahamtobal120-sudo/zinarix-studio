export type GenKey = keyof typeof es;

export function tg(key: GenKey, vars: Record<string, string | number> = {}): string {
  const s = (lang === 'en' ? en : es)[key];
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export const genLang: 'es' | 'en' = lang === 'en' ? 'en' : 'es';
