export type KeyG = keyof typeof es;

export function tg(key: KeyG, vars: Record<string, string | number> = {}): string {
  const s = (lang === 'en' ? en : es)[key];
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export const isEn = (): boolean => lang === 'en';
