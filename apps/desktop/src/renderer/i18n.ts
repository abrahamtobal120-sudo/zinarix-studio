export type Lang = 'es' | 'en';
const LANG_KEY = 'zs.lang';

/** UI language: the saved choice, else the system language (English or Spanish). */
function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'es' || saved === 'en') return saved;
  } catch {
    // storage unavailable: fall back to the system language
  }
  return navigator.language.toLowerCase().startsWith('en') ? 'en' : 'es';
}

export const lang: Lang = detectLang();
const dict: Record<Key, string> = lang === 'en' ? en : es;

/** Saves the UI language; strings are resolved at load, so the caller reloads the window. */
export function setLang(next: Lang): void {
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {
    // storage unavailable: the choice only lasts until the reload
  }
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return dict[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}
