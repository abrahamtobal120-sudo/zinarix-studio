/** A closed box as triangles (mm). */
function box(sx: number, sy: number, sz: number): Float32Array {
  const v = (x: number, y: number, z: number) => [x * sx, y * sy, z * sz];
  const q = (a: number[], b: number[], c: number[], d: number[]) => [
    ...a,
    ...b,
    ...c,
    ...a,
    ...c,
    ...d,
  ];
  return Float32Array.from([
    ...q(v(0, 0, 0), v(0, 1, 0), v(1, 1, 0), v(1, 0, 0)),
    ...q(v(0, 0, 1), v(1, 0, 1), v(1, 1, 1), v(0, 1, 1)),
    ...q(v(0, 0, 0), v(1, 0, 0), v(1, 0, 1), v(0, 0, 1)),
    ...q(v(0, 1, 0), v(0, 1, 1), v(1, 1, 1), v(1, 1, 0)),
    ...q(v(0, 0, 0), v(0, 0, 1), v(0, 1, 1), v(0, 1, 0)),
    ...q(v(1, 0, 0), v(1, 1, 0), v(1, 1, 1), v(1, 0, 1)),
  ]);
}

describe('G-code reader', () => {
  it('reads moves, layers, relative modes, G92 and slicer comments', () => {
    const g = [
      '; generated by PrusaSlicer 2.9.7 on 2026',
      'G21',
      'G90',
      'M82',
      'M104 S215',
      'M140 S60',
      'G28',
      'G92 E0',
      'G1 Z0.2 F3000',
      'G1 X10 Y10 F6000 ; travel',
      'G1 X20 Y10 E1 F1200',
      'G1 X20 Y20 E2',
      'G1 E1.2 F2400 ; retract',
      'G1 Z0.6 ; hop',
      'G1 X10 Y20',
      'G1 Z0.2',
      'G1 E2 ; unretract',
      'G1 X10 Y10 E3',
      'G92 E0',
      'G1 Z0.4',
      'M83',
      'G1 X20 Y10 E0.5',
      'G91',
      'G1 X0 Y10 E0.5',
      'G90',
      'M83',
      'N10 G1 X10 Y20 E0.5*77',
      '; filament used [mm] = 4.5',
      '; total filament used [g] = 0.01',
      '; estimated printing time (normal mode) = 1h 2m 3s',
    ].join('\n');
    const p = parseGcode(g);
    expect(p.layers.map((l) => l.z)).toEqual([0.2, 0.4]);
    expect(p.layers[0]).toMatchObject({ e0: 0, e1: 3 });
    expect(p.layers[1]).toMatchObject({ e0: 3, e1: 6 });
    expect(p.extrude.length / 6).toBe(6);
    // The second-layer relative move ends at (20, 20).
    expect(Array.from(p.extrude.subarray(4 * 6, 4 * 6 + 6))).toEqual(
      [20, 10, 0.4, 20, 20, 0.4].map((n) => Math.fround(n)),
    );
    expect(p.stats).toMatchObject({
      slicer: 'PrusaSlicer 2.9.7',
      slicerTimeS: 3723,
      nozzleTemp: 215,
      bedTemp: 60,
      layers: 2,
      slicerFilamentMm: 4.5,
    });
    // Net filament: retract and unretract cancel (3 on the first layer + 1.5 on the second).
    expect(p.stats.filamentMm).toBeCloseTo(4.5, 5);
    [10, 10, 0.2, 20, 20, 0.4].forEach((v, i) => expect(p.stats.bounds![i]).toBeCloseTo(v, 5));
    expect(describeGcode(p.stats, [220, 220, 250])).toContain('Time: 1 h 2 min');
  });

  it('splits arcs, reads Cura comments and handles inches and odd lines', () => {
    const g =
      ';FLAVOR:Marlin\n;TIME:600\n;Filament used: 1.5m\n;Layer height: 0.2\nG1 Z0.2\nG1 X10 Y0\nG2 X0 Y10 I-10 J0 E5\nM999 garbage\nG1 X\nfoo bar\n';
    const p = parseGcode(g);
    expect(p.stats.slicer).toBe('Cura');
    expect(p.stats.slicerTimeS).toBe(600);
    expect(p.stats.slicerFilamentMm).toBe(1500);
    expect(p.stats.layerHeight).toBe(0.2);
    // A quarter circle of radius 10 in ~1 mm pieces, ending exactly at (0, 10).
    const n = p.extrude.length / 6;
    expect(n).toBeGreaterThan(12);
    expect(p.extrude[(n - 1) * 6 + 3]).toBeCloseTo(0, 5);
    expect(p.extrude[(n - 1) * 6 + 4]).toBeCloseTo(10, 5);
    // Clockwise from (10,0) to (0,10) around the origin goes the long way, through negative y.
    let minY = Infinity;
    for (let i = 0; i < n; i++) minY = Math.min(minY, p.extrude[i * 6 + 4]!);
    expect(minY).toBeLessThan(-9);
    const inch = parseGcode('G20\nG1 Z0.01\nG1 X1 Y0 E0.1\n');
    expect(inch.extrude[3]).toBeCloseTo(25.4, 4);
  });

  it('keeps a spiral (vase mode) as few layers, caps the segments and makes ribbons', () => {
    const lines = ['G1 Z0.2', 'G1 X0 Y0'];
    let e = 0;
    for (let i = 1; i <= 400; i++)
      lines.push(
        `G1 X${(10 * Math.cos(i / 10)).toFixed(3)} Y${(10 * Math.sin(i / 10)).toFixed(3)} Z${(0.2 + i * 0.005).toFixed(4)} E${(e += 0.05).toFixed(3)}`,
      );
    const p = parseGcode(lines.join('\n'));
    expect(p.layers.length).toBeLessThan(60);
    const capped = parseGcode(lines.join('\n'), { maxSegments: 50 });
    expect(capped.extrude.length / 6).toBe(50);
    expect(capped.stats.truncated).toBe(true);
    const t = gcodeTris(p, 100);
    expect(t.length % 9).toBe(0);
    expect(t.length / 9).toBeLessThanOrEqual(4 * 100 + 4);
    expect(parseGcode('GCDE\u0001\u0000').stats.binary).toBe(true);
  });

  it('leaves the start G-code (;TYPE:Custom) out of the size', () => {
    const p = parseGcode(
      [
        ';TYPE:Custom',
        'G1 Z0.3',
        'G1 X5 Y20',
        'G1 X5 Y120 E10',
        ';TYPE:External perimeter',
        'G1 Z0.2',
        'G1 X100 Y100',
        'G1 X110 Y100 E11',
        'G1 X110 Y110 E12',
      ].join('\n'),
    );
    expect(p.layers.length).toBe(1);
    expect(p.layers[0]!.z).toBe(0.2);
    [100, 100, 0.2, 110, 110, 0.2].forEach((v, i) => expect(p.stats.bounds![i]).toBeCloseTo(v, 5));
    // Only custom code: its size is all there is.
    expect(parseGcode(';TYPE:Custom\nG1 Z0.3\nG1 X5 Y20 E1\n').stats.bounds![0]).toBeCloseTo(0, 5);
  });

  it('formats durations', () => {
    expect(parseDuration('1d 2h 3m 4s')).toBe(93784);
    expect(parseDuration('6m 36s')).toBe(396);
    expect(parseDuration('nada')).toBeUndefined();
    expect(formatDuration(396)).toBe('6 min 36 s');
    expect(formatDuration(3723)).toBe('1 h 2 min');
    expect(formatDuration(45)).toBe('45 s');
  });
});

