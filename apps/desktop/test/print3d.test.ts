interface Seen {
  method: string;
  url: string;
  key?: string;
  body: Buffer;
  type?: string;
}

async function body(req: IncomingMessage): Promise<Buffer> {
  const parts: Buffer[] = [];
  for await (const c of req) parts.push(c as Buffer);
  return Buffer.concat(parts);
}

function serve(
  handler: (s: Seen) => { status?: number; json?: unknown },
): Promise<{ url: string; seen: Seen[]; server: Server }> {
  const seen: Seen[] = [];
  const server = createServer(async (req, res) => {
    const s: Seen = {
      method: req.method!,
      url: req.url!,
      ...(req.headers['x-api-key'] ? { key: String(req.headers['x-api-key']) } : {}),
      body: await body(req),
      ...(req.headers['content-type'] ? { type: req.headers['content-type'] } : {}),
    };
    seen.push(s);
    const r = handler(s);
    res.writeHead(r.status ?? 200, { 'Content-Type': 'application/json' });
    res.end(r.json === undefined ? '' : JSON.stringify(r.json));
  });
  return new Promise((ok) =>
    server.listen(0, '127.0.0.1', () =>
      ok({ url: `http://127.0.0.1:${(server.address() as { port: number }).port}`, seen, server }),
    ),
  );
}

