export type EasyKey = keyof typeof es;

export function te(key: EasyKey, vars: Record<string, string | number> = {}): string {
  const s = (lang === 'en' ? en : es)[key];
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
