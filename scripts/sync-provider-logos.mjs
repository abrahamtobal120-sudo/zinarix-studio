#!/usr/bin/env node
// Copies provider logos (Lobe Icons, MIT — https://github.com/lobehub/lobe-icons) into the
// desktop renderer and the website, one SVG per catalog provider id. Monochrome logos use
// `currentColor`, which an <img> cannot inherit, so they are pinned to a dark ink; the UI
// shows every logo on a light tile. Providers without a logo fall back to initials.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const iconsDir = join(dirname(require.resolve('@lobehub/icons-static-svg/package.json')), 'icons');

/** catalog id -> Lobe icon name (the "-color" variant is preferred when it exists). */
const MAP = {
  openai: 'openai',
  anthropic: 'claude',
  'google-gemini': 'gemini',
  'google-vertex': 'vertexai',
  'azure-openai': 'azure',
  'amazon-bedrock': 'bedrock',
  mistral: 'mistral',
  xai: 'xai',
  deepseek: 'deepseek',
  'meta-llama': 'meta',
  cohere: 'cohere',
  ai21: 'ai21',
  openrouter: 'openrouter',
  groq: 'groq',
  cerebras: 'cerebras',
  sambanova: 'sambanova',
  together: 'together',
  fireworks: 'fireworks',
  deepinfra: 'deepinfra',
  perplexity: 'perplexity',
  'huggingface-inference-providers': 'huggingface',
  replicate: 'replicate',
  novita: 'novita',
  hyperbolic: 'hyperbolic',
  'nebius-token-factory': 'nebius',
  'lambda-inference': 'lambda',
  'nvidia-nim': 'nvidia',
  'cloudflare-workers-ai': 'cloudflare',
  'github-models': 'github',
  'ibm-watsonx-ai': 'ibm',
  databricks: 'dbrx',
  'snowflake-cortex': 'snowflake',
  upstage: 'upstage',
  reka: 'reka',
  'alibaba-qwen': 'qwen',
  moonshot: 'kimi',
  'zhipu-zai': 'zhipu',
  minimax: 'minimax',
  'baidu-qianfan': 'wenxin',
  '01-ai': 'yi',
  'tencent-hunyuan': 'hunyuan',
  ollama: 'ollama',
  'lm-studio': 'lmstudio',
  vllm: 'vllm',
  chutes: 'chutes',
  siliconflow: 'siliconcloud',
  featherless: 'featherless',
  'inference-net': 'inference',
  parasail: 'parasail',
  friendli: 'friendli',
  stepfun: 'stepfun',
  'byteplus-modelark': 'doubao',
  venice: 'venice',
};

const targets = [join(root, 'apps/desktop/src/renderer/public/providers'), join(root, 'website/assets/providers')];
for (const t of targets) mkdirSync(t, { recursive: true });

const read = (name) => {
  for (const file of [`${name}-color.svg`, `${name}.svg`]) {
    try {
      return readFileSync(join(iconsDir, file), 'utf8');
    } catch {
      // try next variant
    }
  }
  return null;
};

const done = [];
for (const [id, name] of Object.entries(MAP)) {
  let svg = read(name);
  if (!svg) {
    console.error(`missing icon for ${id} (${name})`);
    continue;
  }
  svg = svg
    .replace(/fill="currentColor"/g, 'fill="#14161f"')
    .replace(/ height="1em"/, ' height="64"')
    .replace(/ width="1em"/, ' width="64"')
    .replace(/ style="[^"]*"/, '');
  for (const t of targets) writeFileSync(join(t, `${id}.svg`), svg);
  done.push(id);
}
const index = `// Generated by scripts/sync-provider-logos.mjs — provider ids that ship a logo.\nexport const PROVIDER_LOGOS: ReadonlySet<string> = new Set(${JSON.stringify(done.sort())});\n`;
writeFileSync(join(root, 'apps/desktop/src/renderer/providerLogos.ts'), index);
writeFileSync(join(root, 'website/assets/providers/index.json'), JSON.stringify(done.sort()) + '\n');
console.log(`${done.length} provider logos written`);
